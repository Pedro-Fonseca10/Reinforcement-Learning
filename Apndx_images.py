# Função auxiliar para gerar gráfico
def plot_and_save(episodes, rewards, title, filename):
    plt.figure(figsize=(8, 4))
    plt.plot(episodes, rewards, marker='o')
    plt.xlabel("Episódio")
    plt.ylabel("Recompensa média")
    plt.title(title)
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(filename, dpi=120)
    plt.close()

